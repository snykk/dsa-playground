#include <cassert>
#include <vector>
#include "sudoku_solver.cpp"

void testSolveValidSudoku() {
    vector<vector<int>> board = {
        {5, 3, 0, 0, 7, 0, 0, 0, 0},
        {6, 0, 0, 1, 9, 5, 0, 0, 0},
        {0, 9, 8, 0, 0, 0, 0, 6, 0},
        {8, 0, 0, 0, 6, 0, 0, 0, 3},
        {4, 0, 0, 8, 0, 3, 0, 0, 1},
        {7, 0, 0, 0, 2, 0, 0, 0, 6},
        {0, 6, 0, 0, 0, 0, 2, 8, 0},
        {0, 0, 0, 4, 1, 9, 0, 0, 5},
        {0, 0, 0, 0, 8, 0, 0, 7, 9}
    };
    assert(solveSudoku(board));
    // Check that all cells are filled
    for (const auto& row : board) {
        for (int cell : row) {
            assert(cell != 0);
        }
    }
}

void testIsValid() {
    vector<vector<int>> board = {
        {5, 3, 0, 0, 7, 0, 0, 0, 0},
        {6, 0, 0, 1, 9, 5, 0, 0, 0},
        {0, 9, 8, 0, 0, 0, 0, 6, 0},
        {8, 0, 0, 0, 6, 0, 0, 0, 3},
        {4, 0, 0, 8, 0, 3, 0, 0, 1},
        {7, 0, 0, 0, 2, 0, 0, 0, 6},
        {0, 6, 0, 0, 0, 0, 2, 8, 0},
        {0, 0, 0, 4, 1, 9, 0, 0, 5},
        {0, 0, 0, 0, 8, 0, 0, 7, 9}
    };
    assert(isValid(board, 0, 2, 1));
    assert(!isValid(board, 0, 2, 5));  // Already in row
    assert(!isValid(board, 0, 2, 6));  // Already in column
}

int main() {
    testSolveValidSudoku();
    testIsValid();
    std::cout << "All tests passed!" << std::endl;
    return 0;
}


def access_char(s: str, index: int) -> str:
    return s[index]

def string_length(s: str) -> int:
    return len(s)

def traverse_string(s: str) -> list:
    return [c for c in s]

def concatenate(s1: str, s2: str) -> str:
    return s1 + s2

def substring(s: str, start: int, end: int) -> str:
    return s[start:end]
